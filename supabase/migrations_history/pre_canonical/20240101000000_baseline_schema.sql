-- ---- providers: public read, self-write ------------------------------------
drop policy if exists providers_select_all on public.providers;
create policy providers_select_all on public.providers for select using (true);
drop policy if exists providers_insert_self on public.providers;
create policy providers_insert_self on public.providers for insert with check (auth.uid() = user_id);
drop policy if exists providers_update_self on public.providers;
create policy providers_update_self on public.providers for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- HARDENING (audit critical #2): even with the self-update policy above, a
-- provider must NOT be able to grant themselves verification / featuring /
-- payment capability / inflated stats. Revoke column-level UPDATE so only the
-- service role (or a trigger) can change them.
revoke update (
  is_approved, is_featured, is_trending,
  verification_status, identity_verified, business_verified,
  stripe_charges_enabled, stripe_payouts_enabled, stripe_onboarding_complete,
  stripe_details_submitted, stripe_account_id,
  rating, average_rating, review_count,
  total_bookings, completed_count, no_show_count, follower_count
) on public.providers from authenticated;

-- ---- clients: strictly self ------------------------------------------------
