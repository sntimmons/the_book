-- =============================================================================
-- The Book — BASELINE SCHEMA CAPTURE
-- =============================================================================
-- This is NOT the original migration history. The database was built manually
-- in the Supabase dashboard, so no migration files existed. This file is a
-- best-effort baseline reconstructed from CODE ANALYSIS (every supabase.from()
-- call, every .select()/.insert()/.update() in the app) plus the column lists
-- confirmed via live REST probes during the security-hardening session.
--
-- CONFIDENCE:
--   * providers / bookings / clients  -> column lists CONFIRMED via live probe.
--   * all other tables                -> columns INFERRED from code usage; types
--                                        are reasonable guesses. Production may
--                                        have additional columns not captured here.
--
-- SAFETY:
--   * Every CREATE TABLE uses IF NOT EXISTS, so running this against a database
--     that already has these tables is a no-op for those tables (it will NOT
--     add missing columns to an existing table — CREATE TABLE IF NOT EXISTS
--     skips the whole statement if the table exists).
--   * Buckets use ON CONFLICT DO NOTHING. Triggers/functions use CREATE OR
--     REPLACE + DROP TRIGGER IF EXISTS.
--   * RLS POLICIES are the *intended* hardened baseline (from the audit). They
--     use DROP POLICY IF EXISTS + CREATE POLICY, which means running this on an
--     EXISTING production DB would REPLACE whatever policies are live. Do NOT
--     blindly run the RLS section against production — see supabase/README.md.
--
-- Primary use: bootstrap a FRESH Supabase project to a working approximation of
-- production. See supabase/README.md for the full engineer handoff + gaps list.
-- =============================================================================

