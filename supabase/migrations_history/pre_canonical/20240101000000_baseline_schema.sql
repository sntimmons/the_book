  auth.uid() = client_id
  or provider_id in (select id from public.providers where user_id = auth.uid())
) with check (
  auth.uid() = client_id
  or provider_id in (select id from public.providers where user_id = auth.uid())
);
drop policy if exists messages_select_participant on public.messages;
create policy messages_select_participant on public.messages for select using (
  conversation_id in (
    select id from public.conversation
    where client_id = auth.uid()
