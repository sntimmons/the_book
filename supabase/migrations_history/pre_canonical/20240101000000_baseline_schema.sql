-- 11. DENORMALIZED-COUNT TRIGGERS
-- Keep like/save/comment/reply counts in sync so the client never has to.
-- =============================================================================

create or replace function public.bump_post_like_count() returns trigger language plpgsql as $$
begin
  if (tg_op = 'INSERT') then
    update public.posts set like_count = like_count + 1 where id = new.post_id;
  elsif (tg_op = 'DELETE') then
    update public.posts set like_count = greatest(0, like_count - 1) where id = old.post_id;
  end if;
  return null;
end; $$;
drop trigger if exists trg_post_like_count on public.post_likes;
create trigger trg_post_like_count after insert or delete on public.post_likes
  for each row execute function public.bump_post_like_count();

